/** A representative real photo for a whole category — used on category tiles
 * and anywhere a specific dish photo isn't available (e.g. a backend log,
 * which only carries category/subtype, not an image). */
export function categoryVisual(category: string): { emoji: string; tint: string; photo?: string } {
  const cat = CATEGORIES.find((c) => c.name === category);
  const firstDish = DISHES.find((d) => d.category === category);
  return {
    emoji: cat?.emoji ?? "🍽️",
    tint: CATEGORY_TINT[category] ?? "from-slate-500/30 to-slate-900/40",
    photo: firstDish?.photo,
  };
}
